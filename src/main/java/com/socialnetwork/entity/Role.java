package com.socialnetwork.entity;

/**
 * Роли пользователей в системе.
 *
 * <p>Определяет уровень доступа пользователя к функциям приложения.
 * Используется в Spring Security для настройки правил авторизации
 * через аннотации {@code @PreAuthorize("hasRole('ADMIN')")} и т.д.</p>
 *
 * <p>Префикс {@code ROLE_} является обязательным соглашением Spring Security:
 * фреймворк автоматически ищет именно такой префикс при проверке ролей
 * через метод {@code hasRole()}. При использовании {@code hasAuthority()}
 * префикс не требуется, но {@code ROLE_} уже стал де-факто стандартом.</p>
 */
public enum Role {

    /**
     * Обычный пользователь социальной сети.
     * Может создавать посты, комментировать, отправлять заявки в друзья,
     * писать сообщения и вступать в группы.
     */
    ROLE_USER, // Стандартная роль, присваиваемая при регистрации по умолчанию

    /**
     * Администратор платформы.
     * Имеет доступ к административным функциям: блокировка пользователей,
     * удаление контента, просмотр системной статистики.
     * Администраторы назначаются вручную — через БД или специальный эндпоинт.
     */
    ROLE_ADMIN // Привилегированная роль с расширенными правами доступа
}
