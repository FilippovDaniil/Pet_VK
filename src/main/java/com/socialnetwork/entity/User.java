package com.socialnetwork.entity;

// Импорты из Jakarta Persistence (JPA) — стандарт для работы с реляционными БД в Java EE / Jakarta EE.
// Spring Boot 3.x использует Jakarta EE 9+, поэтому пространство имён "jakarta", а не старое "javax".
import jakarta.persistence.*;
// Аннотации Lombok — библиотека для автогенерации шаблонного кода (геттеры, сеттеры, конструкторы и т.д.).
// Lombok обрабатывается во время компиляции: итоговый .class файл содержит все методы.
import lombok.*;
// Hibernate-специфичные аннотации для автоматической установки временных меток при создании/обновлении записи.
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

// LocalDateTime — дата и время без информации о часовом поясе. Подходит для хранения в БД,
// где временная зона задаётся на уровне сервера/JVM, а не каждой записи.
import java.time.LocalDateTime;

/**
 * Сущность пользователя социальной сети.
 *
 * <p>Представляет зарегистрированного пользователя платформы. Хранит учётные данные,
 * профильную информацию, роль и статус блокировки. Является центральной сущностью
 * системы — практически все остальные сущности (посты, комментарии, сообщения)
 * ссылаются на пользователя через внешние ключи.</p>
 *
 * <p>Таблица БД: {@code users}</p>
 *
 * @see Role
 */
@Entity
// @Entity сообщает JPA/Hibernate, что этот класс является управляемой сущностью.
// Hibernate будет отслеживать изменения объектов этого класса в рамках Persistence Context
// и автоматически синхронизировать их с БД при коммите транзакции.
@Table(name = "users")
// @Table явно указывает имя таблицы в БД. Без этой аннотации Hibernate использовал бы
// имя класса ("User"), но "users" — общепринятое соглашение (множественное число, snake_case).
@Getter
// Lombok генерирует публичный геттер для каждого поля: getId(), getEmail(), getFirstName() и т.д.
// Это устраняет необходимость писать сотни строк шаблонного кода вручную.
@Setter
// Lombok генерирует публичный сеттер для каждого поля: setEmail(), setFirstName() и т.д.
// Вместе с @Getter обеспечивает стандартный JavaBean-интерфейс, необходимый многим фреймворкам.
@Builder
// Lombok реализует паттерн проектирования "Строитель" (Builder).
// Позволяет создавать объекты так: User.builder().email("a@b.com").firstName("Иван").build()
// Это намного читаемее конструктора с 10+ параметрами.
@NoArgsConstructor
// Lombok генерирует конструктор без аргументов: public User() {}
// ОБЯЗАТЕЛЕН для JPA: Hibernate создаёт объекты через рефлексию, вызывая конструктор без аргументов,
// а затем заполняет поля через сеттеры или напрямую через рефлексию.
@AllArgsConstructor
// Lombok генерирует конструктор со всеми полями класса в порядке их объявления.
// НЕОБХОДИМ для корректной работы @Builder: паттерн Builder использует его внутри.
public class User {

    /**
     * Уникальный идентификатор пользователя в базе данных.
     * Генерируется автоматически базой данных при вставке новой записи.
     * Используется как первичный ключ и для создания внешних ключей в других таблицах.
     */
    @Id
    // @Id обозначает поле как первичный ключ (PRIMARY KEY) таблицы.
    // Каждая JPA-сущность обязана иметь ровно одно поле с @Id.
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    // @GeneratedValue задаёт стратегию генерации первичного ключа.
    // IDENTITY: значение генерирует сама БД при INSERT (AUTO_INCREMENT в MySQL, SERIAL в PostgreSQL).
    // Это означает, что id объекта остаётся null до первого сохранения в БД.
    // Альтернатива SEQUENCE требует отдельного объекта-последовательности в БД и даёт
    // лучшую производительность при пакетной вставке, но IDENTITY проще в настройке.
    private Long id;

    /**
     * Адрес электронной почты пользователя.
     * Используется как логин при аутентификации через Spring Security.
     * Должен быть уникальным в рамках всей платформы.
     */
    @Column(nullable = false, unique = true, length = 255)
    // nullable = false: колонка получает ограничение NOT NULL в DDL-схеме БД.
    //   Email обязателен — без него невозможна аутентификация.
    // unique = true: Hibernate создаёт уникальный индекс на эту колонку,
    //   предотвращая регистрацию двух пользователей с одинаковым email.
    // length = 255: максимальная длина строки. 255 — стандарт для email согласно RFC 5321.
    //   Также это максимум для VARCHAR без переключения на TEXT в большинстве СУБД.
    private String email;

    /**
     * Хэш пароля пользователя (BCrypt).
     * Никогда не хранится в открытом виде — только результат хэширования через BCryptPasswordEncoder.
     * Может быть null для пользователей, вошедших через OAuth (VK, Google и т.д.).
     */
    @Column(length = 255)
    // nullable не указан — значит колонка допускает NULL (поведение по умолчанию).
    // Это намеренно: OAuth-пользователи могут не иметь пароля.
    // length = 255: BCrypt всегда выдаёт строку из 60 символов, но 255 — запас на будущее.
    private String password;

    /**
     * Имя пользователя (например, "Иван").
     */
    @Column(name = "first_name", nullable = false, length = 100)
    // name = "first_name": маппинг на колонку с именем в snake_case — стандарт SQL-именования.
    //   По умолчанию Hibernate использовал бы "firstname" (без разделителя).
    // nullable = false: имя обязательно при регистрации — без него нельзя создать профиль.
    // length = 100: разумный предел для имени, избегающий переполнения при отображении в UI.
    private String firstName;

    /**
     * Фамилия пользователя (например, "Иванов").
     */
    @Column(name = "last_name", nullable = false, length = 100)
    // Аналогично firstName — фамилия обязательна и ограничена 100 символами.
    // snake_case в name = "last_name" соответствует соглашениям SQL.
    private String lastName;

    /**
     * URL аватара пользователя — ссылка на изображение профиля.
     * Хранится как ссылка на файл во внешнем хранилище (S3, MinIO и т.п.),
     * а не само изображение в виде байт в БД (это плохая практика).
     */
    @Column(name = "avatar_url", columnDefinition = "TEXT")
    // columnDefinition = "TEXT": тип данных колонки задаётся явно как TEXT в SQL.
    // URL может быть длиннее 255 символов (особенно подписанные URL к S3),
    // поэтому VARCHAR(255) не подходит.
    // Колонка допускает NULL — у пользователя может не быть аватара (используется заглушка).
    private String avatarUrl;

    /**
     * Краткая биография или описание профиля пользователя.
     * Аналог поля "О себе" в VK. Произвольный текст без ограничения длины.
     */
    @Column(columnDefinition = "TEXT")
    // TEXT: без ограничения длины — пользователь может написать развёрнутую биографию.
    // Допускает NULL — биография необязательна.
    private String bio;

    /**
     * Роль пользователя в системе (обычный пользователь или администратор).
     * Определяет уровень доступа к функциям платформы.
     *
     * @see Role
     */
    @Enumerated(EnumType.STRING)
    // @Enumerated задаёт способ хранения enum в БД.
    // EnumType.STRING: хранит строковое имя константы ("ROLE_USER", "ROLE_ADMIN").
    // НИКОГДА не используй EnumType.ORDINAL: он хранит числовой индекс (0, 1, 2...),
    // что делает данные хрупкими — добавление нового элемента enum в середину
    // сломает все существующие записи в БД.
    @Column(nullable = false, length = 20)
    // nullable = false: роль обязательна — каждый пользователь должен иметь роль.
    // length = 20: достаточно для "ROLE_USER" (9 символов) и "ROLE_ADMIN" (10 символов).
    @Builder.Default
    // @Builder.Default: указывает значение по умолчанию при использовании Builder.
    // БЕЗ этой аннотации Builder проигнорирует инициализатор "= Role.ROLE_USER"
    // и установит null, что нарушит ограничение NOT NULL в БД.
    private Role role = Role.ROLE_USER; // По умолчанию каждый новый пользователь получает роль обычного пользователя

    /**
     * Флаг блокировки учётной записи.
     * Если {@code true} — пользователь заблокирован администратором.
     * Spring Security проверяет это поле через метод {@code isAccountNonLocked()}.
     */
    @Column(name = "is_banned", nullable = false)
    // name = "is_banned": стандартный префикс "is_" для булевых колонок в SQL.
    // nullable = false: поле NOT NULL — значение всегда должно быть явным (true или false).
    //   Это важно: NULL в булевом поле — источник трудноуловимых багов (троичная логика SQL).
    @Builder.Default
    // @Builder.Default гарантирует, что новые пользователи создаются незаблокированными по умолчанию.
    private boolean banned = false; // По умолчанию пользователь не заблокирован

    /**
     * Дата и время создания учётной записи.
     * Устанавливается автоматически Hibernate при первом сохранении объекта в БД.
     * Неизменна после создания — представляет историческую дату регистрации.
     */
    @CreationTimestamp
    // @CreationTimestamp: Hibernate автоматически присваивает текущее время при выполнении INSERT.
    // Это надёжнее, чем устанавливать время в сервисном слое — значение
    // гарантированно выставляется в момент записи в БД, а не в момент создания объекта в памяти.
    @Column(name = "created_at", updatable = false)
    // updatable = false: Hibernate игнорирует это поле при UPDATE.
    // Дата регистрации — неизменяемый исторический факт. Без этого флага
    // случайное обновление сущности могло бы сбросить дату регистрации.
    private LocalDateTime createdAt;

    /**
     * Дата и время последнего обновления учётной записи.
     * Автоматически обновляется Hibernate при каждом изменении и сохранении объекта.
     * Позволяет отслеживать активность и актуальность данных профиля.
     */
    @UpdateTimestamp
    // @UpdateTimestamp: Hibernate обновляет это поле текущим временем при каждом UPDATE.
    // Полезно для функций типа "последний раз онлайн" или для инвалидации кэша.
    // В отличие от @CreationTimestamp, обновляется при каждом сохранении (INSERT и UPDATE).
    @Column(name = "updated_at")
    // updatable здесь не ограничен — значение должно меняться при каждом обновлении профиля.
    private LocalDateTime updatedAt;
}
