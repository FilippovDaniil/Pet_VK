package com.socialnetwork.entity;

/**
 * Роль участника в группе (сообществе) социальной сети.
 *
 * <p>Определяет уровень прав пользователя внутри конкретной группы.
 * Не путать с системной ролью ({@link Role}) — это роль только в рамках одной группы.
 * Один и тот же пользователь может быть ADMIN в одной группе и MEMBER в другой.
 */
public enum GroupMemberRole {

    /**
     * Обычный участник группы.
     * Может читать посты группы. Назначается автоматически при вступлении.
     */
    MEMBER, // обычный участник, назначается по умолчанию при joinGroup()

    /**
     * Администратор группы.
     * Может публиковать посты от имени группы и назначать других участников администраторами.
     * Создатель группы автоматически получает эту роль при создании.
     */
    ADMIN   // повышенные права: публикация постов, назначение других администраторов
}
