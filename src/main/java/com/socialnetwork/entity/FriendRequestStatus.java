package com.socialnetwork.entity;

/**
 * Статус заявки в друзья между пользователями.
 *
 * <p>Отражает текущее состояние заявки в жизненном цикле.
 * Хранится в базе данных как строка (EnumType.STRING), что делает данные
 * читаемыми и устойчивыми к изменению порядка констант.
 */
public enum FriendRequestStatus {

    /**
     * Заявка отправлена и ожидает ответа адресата.
     * Начальный статус — устанавливается при создании заявки.
     */
    PENDING,    // ожидает принятия или отклонения

    /**
     * Адресат принял заявку — пользователи стали друзьями.
     * Только заявки с этим статусом учитываются при получении списка друзей.
     */
    ACCEPTED,   // дружба установлена

    /**
     * Адресат отклонил заявку — дружба не установлена.
     * Запись остаётся в базе данных (история) — это предотвращает
     * повторную отправку заявки сразу после отклонения.
     */
    DECLINED    // заявка отклонена
}
