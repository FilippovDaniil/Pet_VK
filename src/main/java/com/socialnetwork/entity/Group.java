package com.socialnetwork.entity;

// Импорты JPA для объявления сущности и описания связей между таблицами
import jakarta.persistence.*;
// Аннотации Lombok для генерации шаблонного кода
import lombok.*;
// Hibernate-аннотация для автоматической простановки временной метки при создании записи
import org.hibernate.annotations.CreationTimestamp;

// LocalDateTime для хранения даты и времени без информации о часовом поясе
import java.time.LocalDateTime;

/**
 * Сущность группы (сообщества) в социальной сети.
 *
 * <p>Группа — объединение пользователей вокруг общей темы или интереса.
 * Аналог сообщества в VK. Группа имеет владельца, который обладает
 * максимальными правами внутри неё (назначение администраторов, удаление участников и т.д.).</p>
 *
 * <p>Связанные сущности:</p>
 * <ul>
 *   <li>{@link GroupMember} — участники группы (связь реализована через отдельную таблицу)</li>
 *   <li>{@link Post} — публикации в группе</li>
 * </ul>
 *
 * <p>Таблица БД: {@code groups}</p>
 *
 * <p><b>Важно:</b> слово {@code groups} является зарезервированным в некоторых СУБД (например, MySQL),
 * поэтому при необходимости Hibernate экранирует его в DDL-запросах.</p>
 *
 * @see GroupMember
 * @see User
 */
@Entity
// Объявляет класс управляемой JPA-сущностью.
// Hibernate отслеживает изменения объектов этого типа в Persistence Context.
@Table(name = "groups")
// Явно задаём имя таблицы. "groups" — зарезервированное слово в ряде СУБД,
// но Spring Boot / Hibernate корректно обрабатывает это при формировании SQL-запросов.
@Getter
// Lombok: генерирует геттеры для всех полей
@Setter
// Lombok: генерирует сеттеры для всех полей
@Builder
// Lombok: паттерн Builder — Group.builder().name("Java разработчики").owner(user).build()
@NoArgsConstructor
// Lombok: конструктор без аргументов — обязателен для JPA (Hibernate создаёт объекты через рефлексию)
@AllArgsConstructor
// Lombok: конструктор со всеми полями — необходим для работы @Builder
public class Group {

    /**
     * Уникальный идентификатор группы, генерируется базой данных автоматически.
     */
    @Id
    // Первичный ключ таблицы "groups"
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    // IDENTITY: значение генерирует БД при INSERT (AUTO_INCREMENT / SERIAL).
    // id будет null до первого сохранения объекта через репозиторий.
    private Long id;

    /**
     * Название группы (сообщества).
     * Публично отображается в интерфейсе и в результатах поиска.
     * Обязательное поле с ограничением длины.
     */
    @Column(nullable = false, length = 100)
    // nullable = false: название обязательно — группа без названия не имеет смысла (NOT NULL в БД).
    // length = 100: разумный предел для отображения в UI. Слишком длинные названия
    // ухудшают пользовательский опыт и могут ломать вёрстку.
    private String name;

    /**
     * Описание группы — информация о теме, правилах или целях сообщества.
     * Необязательное поле (может быть {@code null}).
     */
    @Column(columnDefinition = "TEXT")
    // TEXT: без ограничения длины — владелец может написать подробное описание.
    // Допускает NULL: группа может существовать без описания.
    private String description;

    /**
     * URL аватара (логотипа) группы — ссылка на изображение во внешнем хранилище.
     * {@code null} если у группы нет своего изображения (используется заглушка).
     */
    @Column(name = "avatar_url", columnDefinition = "TEXT")
    // TEXT: URL может быть длиннее 255 символов (CDN, подписанные S3-ссылки).
    // Допускает NULL: аватар необязателен.
    private String avatarUrl;

    /**
     * Владелец группы — пользователь, создавший сообщество.
     * Имеет максимальные права в группе. Обязательное поле.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    // @ManyToOne: один пользователь может владеть множеством групп (N:1).
    // fetch = FetchType.LAZY: данные владельца загружаются только при обращении к полю owner.
    // При получении списка групп (например, в поиске) загрузка данных каждого
    // владельца была бы излишней нагрузкой — LAZY предотвращает это.
    @JoinColumn(name = "owner_id", nullable = false)
    // owner_id: внешний ключ на таблицу "users".
    // nullable = false: группа обязана иметь владельца (NOT NULL в БД).
    // При удалении пользователя-владельца необходима бизнес-логика: передача прав или удаление группы.
    private User owner;

    /**
     * Дата и время создания группы.
     * Устанавливается автоматически Hibernate при сохранении.
     * После создания не изменяется.
     */
    @CreationTimestamp
    // Hibernate простанавливает текущее время при INSERT. Это надёжнее, чем делать это
    // вручную в сервисном слое — значение фиксируется в момент записи в БД.
    @Column(name = "created_at", updatable = false)
    // updatable = false: дата создания группы неизменна — это исторический факт.
    // Без этого флага случайный вызов save() мог бы обновить дату создания.
    private LocalDateTime createdAt;
}
