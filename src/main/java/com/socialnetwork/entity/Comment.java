package com.socialnetwork.entity;

// Импорты JPA для объявления сущности и настройки связей с другими таблицами
import jakarta.persistence.*;
// Аннотации Lombok для автогенерации кода (геттеры, сеттеры, Builder, конструкторы)
import lombok.*;
// Hibernate-аннотации для автоматической простановки временных меток
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

// LocalDateTime для хранения даты и времени без информации о часовом поясе
import java.time.LocalDateTime;

/**
 * Сущность комментария к публикации.
 *
 * <p>Комментарий — реакция пользователя на конкретный пост в виде текста.
 * Аналог комментария под записью в VK. Комментарий всегда связан с автором
 * (кто оставил) и с постом (под каким постом).</p>
 *
 * <p>Каждый комментарий принадлежит ровно одному посту и ровно одному автору.
 * Иерархические комментарии (ответы на комментарии) в данной реализации не поддерживаются.</p>
 *
 * <p>Таблица БД: {@code comments}</p>
 *
 * @see Post
 * @see User
 */
@Entity
// Объявляет класс JPA-сущностью. Hibernate управляет её жизненным циклом:
// отслеживает изменения в Persistence Context и синхронизирует с БД при коммите транзакции.
@Table(name = "comments")
// Имя таблицы в БД. Явное указание предотвращает зависимость от настроек Hibernate
// по умолчанию (naming strategy может по-разному транслировать имя класса).
@Getter
// Lombok: генерирует публичные геттеры для всех полей
@Setter
// Lombok: генерирует публичные сеттеры для всех полей
@Builder
// Lombok: паттерн Builder — Comment.builder().text("Отличный пост!").author(user).post(post).build()
@NoArgsConstructor
// Lombok: конструктор без аргументов, обязательный для JPA-сущностей
@AllArgsConstructor
// Lombok: конструктор со всеми полями, необходимый для корректной работы @Builder
public class Comment {

    /**
     * Уникальный идентификатор комментария, генерируется базой данных.
     */
    @Id
    // Первичный ключ таблицы "comments"
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    // IDENTITY: БД генерирует значение автоматически (AUTO_INCREMENT / SERIAL).
    // Значение id будет null до первого сохранения объекта в репозиторий.
    private Long id;

    /**
     * Автор комментария — пользователь, оставивший комментарий.
     * Обязательное поле: каждый комментарий принадлежит конкретному пользователю.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    // @ManyToOne: один пользователь может оставлять много комментариев,
    // каждый комментарий принадлежит ровно одному автору (связь N:1).
    // fetch = FetchType.LAZY: "ленивая" загрузка — данные пользователя не загружаются
    // из БД вместе с комментарием. Загрузка произойдёт только при обращении к полю author.
    // Это предотвращает проблему N+1: при загрузке 100 комментариев не выполняются
    // 100 лишних запросов за данными авторов.
    @JoinColumn(name = "author_id", nullable = false)
    // name = "author_id": имя колонки внешнего ключа в таблице "comments".
    // nullable = false: ограничение NOT NULL в БД — комментарий не может быть анонимным.
    private User author;

    /**
     * Пост, к которому относится комментарий.
     * Обязательное поле: комментарий не может существовать без привязки к посту.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    // @ManyToOne: один пост может иметь много комментариев,
    // каждый комментарий привязан ровно к одному посту.
    // LAZY-загрузка: при получении комментария не нужно автоматически тянуть весь пост
    // со всеми его полями — это лишняя нагрузка на БД.
    @JoinColumn(name = "post_id", nullable = false)
    // post_id: внешний ключ, указывающий на id в таблице "posts".
    // nullable = false: комментарий обязан быть привязан к посту — осиротевших комментариев нет.
    private Post post;

    /**
     * Текстовое содержимое комментария.
     * Обязательное поле — пустые комментарии недопустимы.
     */
    @Column(columnDefinition = "TEXT", nullable = false)
    // TEXT: без ограничения длины — комментарий может быть развёрнутым.
    // nullable = false: текст обязателен — комментарий должен содержать хоть что-то.
    // Дополнительная валидация на пустую строку должна выполняться на уровне сервиса или DTO.
    private String text;

    /**
     * Дата и время создания комментария.
     * Устанавливается автоматически Hibernate при первом сохранении.
     * После создания не изменяется.
     */
    @CreationTimestamp
    // Hibernate автоматически простанавливает текущее время при INSERT.
    // Надёжнее ручной установки в сервисном слое, так как значение
    // фиксируется непосредственно в момент записи в БД.
    @Column(name = "created_at", updatable = false)
    // updatable = false: запрещает изменение даты создания при обновлении сущности.
    // Дата первого написания комментария — это исторический факт.
    private LocalDateTime createdAt;

    /**
     * Дата и время последнего редактирования комментария.
     * Обновляется автоматически Hibernate при каждом изменении комментария.
     */
    @UpdateTimestamp
    // Hibernate обновляет это поле текущим временем при каждом UPDATE.
    // Если пользователь отредактировал текст комментария — updatedAt обновится автоматически.
    // Интерфейс может показывать пометку "изменено" если updatedAt != createdAt.
    @Column(name = "updated_at")
    private LocalDateTime updatedAt;
}
