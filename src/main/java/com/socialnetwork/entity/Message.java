package com.socialnetwork.entity;

// Импорты JPA для маппинга класса на таблицу БД и настройки связей
import jakarta.persistence.*;
// Аннотации Lombok для автогенерации геттеров, сеттеров, конструкторов и Builder
import lombok.*;
// Hibernate-аннотация для автоматической установки временной метки при создании записи
import org.hibernate.annotations.CreationTimestamp;

// LocalDateTime для хранения даты и времени без часового пояса
import java.time.LocalDateTime;

/**
 * Сущность личного сообщения между пользователями.
 *
 * <p>Представляет единицу коммуникации в системе личных сообщений платформы.
 * Аналог личного сообщения в VK. Каждое сообщение имеет конкретного отправителя
 * и конкретного получателя (переписка один-на-один, без групповых чатов).</p>
 *
 * <p>Сообщения не редактируются и не удаляются в данной реализации
 * (нет {@code @UpdateTimestamp} и флага {@code deleted}), что упрощает логику,
 * но ограничивает функциональность.</p>
 *
 * <p>Таблица БД: {@code messages}</p>
 *
 * @see User
 */
@Entity
// Объявляет класс управляемой JPA-сущностью: Hibernate отслеживает её состояние
// и синхронизирует с БД в рамках транзакции.
@Table(name = "messages")
// Явное имя таблицы "messages" в snake_case — стандарт SQL-именования.
@Getter
// Lombok: генерирует геттеры для всех полей — getId(), getText(), getSender() и т.д.
@Setter
// Lombok: генерирует сеттеры для всех полей — setRead(), setText() и т.д.
@Builder
// Lombok: паттерн Builder для удобного создания объектов:
// Message.builder().sender(user1).recipient(user2).text("Привет!").build()
@NoArgsConstructor
// Lombok: конструктор без аргументов. ОБЯЗАТЕЛЕН для JPA:
// Hibernate создаёт объекты через рефлексию, вызывая именно этот конструктор.
@AllArgsConstructor
// Lombok: конструктор со всеми полями. НЕОБХОДИМ для корректной работы @Builder.
public class Message {

    /**
     * Уникальный идентификатор сообщения, генерируется базой данных.
     */
    @Id
    // Первичный ключ таблицы "messages"
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    // IDENTITY: БД автоматически генерирует значение при INSERT (AUTO_INCREMENT / SERIAL).
    // Это означает, что id будет null до момента сохранения через репозиторий.
    private Long id;

    /**
     * Отправитель сообщения — пользователь, написавший сообщение.
     * Обязательное поле: сообщение не может быть анонимным.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    // @ManyToOne: один пользователь может отправить много сообщений (N:1).
    // fetch = FetchType.LAZY: отправитель загружается из БД только при обращении к полю sender.
    // При загрузке истории переписки (список сообщений) данные всех отправителей
    // не подтягиваются автоматически — это предотвращает лишние SQL-запросы.
    @JoinColumn(name = "sender_id", nullable = false)
    // sender_id: внешний ключ на таблицу users.
    // nullable = false: каждое сообщение должно иметь отправителя — NOT NULL в схеме БД.
    private User sender;

    /**
     * Получатель сообщения — пользователь, которому адресовано сообщение.
     * Обязательное поле: сообщение должно быть кому-то адресовано.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    // @ManyToOne: один пользователь может получить много сообщений (N:1).
    // LAZY-загрузка: данные получателя загружаются только при необходимости.
    @JoinColumn(name = "recipient_id", nullable = false)
    // recipient_id: внешний ключ на таблицу users (другой пользователь, не отправитель).
    // nullable = false: сообщение без адресата не имеет смысла.
    private User recipient;

    /**
     * Текстовое содержимое сообщения.
     * Обязательное поле — пустые сообщения не сохраняются.
     */
    @Column(columnDefinition = "TEXT", nullable = false)
    // TEXT: без ограничения длины — пользователь может отправить длинное сообщение.
    // nullable = false: сообщение обязано содержать текст.
    // В более сложной реализации можно допустить NULL, если сообщение содержит только вложения.
    private String text;

    /**
     * Флаг прочтения сообщения получателем.
     * {@code false} — сообщение ещё не прочитано (новое/непрочитанное).
     * {@code true} — получатель открыл и просмотрел сообщение.
     * Используется для отображения счётчика непрочитанных сообщений.
     */
    @Column(name = "is_read", nullable = false)
    // is_read: стандартный префикс "is_" для булевых колонок в SQL.
    // nullable = false: NOT NULL в БД — статус прочтения всегда должен быть определён.
    // NULL в булевом поле создаёт трёхзначную логику (true / false / unknown), что недопустимо.
    @Builder.Default
    // @Builder.Default: при использовании Builder обеспечивает значение по умолчанию.
    // БЕЗ этой аннотации Builder установил бы false автоматически (дефолт для boolean),
    // но явное указание делает намерение кода очевидным.
    private boolean read = false; // Новое сообщение по умолчанию непрочитано

    /**
     * Дата и время отправки сообщения.
     * Устанавливается автоматически Hibernate при сохранении.
     * После создания не изменяется — сообщения не редактируются.
     */
    @CreationTimestamp
    // Hibernate выставляет текущее время при INSERT — это и есть момент "отправки" сообщения.
    // Значение фиксируется в момент записи в БД, а не создания объекта в памяти.
    @Column(name = "created_at", updatable = false)
    // updatable = false: дата отправки неизменна. В отличие от постов, сообщения
    // нельзя редактировать в данной реализации — поэтому нет @UpdateTimestamp.
    private LocalDateTime createdAt;
}
