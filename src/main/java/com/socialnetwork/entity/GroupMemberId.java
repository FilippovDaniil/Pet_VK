package com.socialnetwork.entity;

// @Column нужен для явного указания имён колонок составного ключа
import jakarta.persistence.Column;
// @Embeddable помечает класс как встраиваемый составной ключ
import jakarta.persistence.Embeddable;
// Аннотации Lombok для генерации шаблонного кода
import lombok.*;

// Serializable обязателен для всех классов, используемых как составной первичный ключ в JPA.
// JPA-спецификация требует, чтобы классы идентификаторов реализовывали Serializable,
// так как они могут сериализоваться в кэше второго уровня (L2 Cache) или передаваться по сети.
import java.io.Serializable;

/**
 * Составной первичный ключ для сущности {@link GroupMember}.
 *
 * <p>Содержит два поля: идентификатор группы и идентификатор пользователя.
 * Их комбинация уникально идентифицирует запись об участии пользователя в группе,
 * исключая дублирование: один пользователь не может состоять в одной группе дважды.</p>
 *
 * <p>Класс помечен {@code @Embeddable}, что позволяет JPA встраивать его поля
 * в таблицу владельца ({@code group_members}) без создания отдельной таблицы.</p>
 *
 * <p><b>Требования JPA к классу составного ключа:</b></p>
 * <ol>
 *   <li>Должен реализовывать {@link Serializable}</li>
 *   <li>Должен иметь конструктор без аргументов</li>
 *   <li>Должен корректно реализовывать {@code equals()} и {@code hashCode()} —
 *       JPA использует их для сравнения ключей в Persistence Context и кэшах</li>
 * </ol>
 *
 * @see GroupMember
 */
@Embeddable
// @Embeddable: обозначает класс как встраиваемый объект-значение (Value Object).
// Поля этого класса будут частью таблицы той сущности, которая его использует через @EmbeddedId.
// В отличие от @Entity, @Embeddable класс не имеет собственной таблицы и идентификатора.
@Getter
// Lombok: генерирует геттеры — getGroupId(), getUserId()
@Setter
// Lombok: генерирует сеттеры — setGroupId(), setUserId()
@NoArgsConstructor
// Lombok: конструктор без аргументов. ОБЯЗАТЕЛЕН по требованию JPA-спецификации
// к классам, используемым в качестве составного ключа.
@AllArgsConstructor
// Lombok: конструктор со всеми полями — удобен для создания ключа: new GroupMemberId(groupId, userId)
@EqualsAndHashCode
// Lombok: генерирует корректные методы equals() и hashCode() на основе ВСЕХ полей класса.
// КРИТИЧЕСКИ ВАЖНО: JPA использует equals() и hashCode() для:
//   1. Поиска сущностей в Persistence Context (First Level Cache)
//   2. Сравнения ключей при работе с коллекциями (@OneToMany и т.д.)
//   3. Корректного слияния (merge) отсоединённых сущностей
// БЕЗ правильной реализации этих методов возможны трудноуловимые баги:
// Hibernate может не найти уже загруженную сущность и сделать лишний запрос к БД.
public class GroupMemberId implements Serializable {
    // implements Serializable — обязательное требование JPA-спецификации для классов ключей.
    // Позволяет сериализацию объекта (например, в распределённом кэше или при передаче между JVM).

    /**
     * Идентификатор группы — часть составного первичного ключа.
     * Соответствует {@code id} в таблице {@code groups}.
     */
    @Column(name = "group_id")
    // Явно задаём имя колонки в БД. Это то же имя, что и в @JoinColumn в GroupMember —
    // они должны совпадать для корректной работы @MapsId.
    private Long groupId;

    /**
     * Идентификатор пользователя — часть составного первичного ключа.
     * Соответствует {@code id} в таблице {@code users}.
     */
    @Column(name = "user_id")
    // Явно задаём имя колонки. Должно совпадать с @JoinColumn(name = "user_id") в GroupMember.
    private Long userId;
}
