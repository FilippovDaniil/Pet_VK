package com.socialnetwork.entity;

// Импорты JPA для маппинга сущности на таблицу и управления связями между таблицами
import jakarta.persistence.*;
// Аннотации Lombok для генерации шаблонного кода (геттеры, сеттеры, конструкторы, Builder)
import lombok.*;
// Hibernate-аннотации для автоматической простановки временных меток
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

// LocalDateTime для хранения даты/времени без привязки к часовому поясу
import java.time.LocalDateTime;

/**
 * Сущность публикации (поста) в социальной сети.
 *
 * <p>Пост — основная единица пользовательского контента на платформе. Аналог записи
 * на стене в VK. Пост может быть опубликован:</p>
 * <ul>
 *   <li>В личной ленте пользователя (поле {@code group} равно {@code null})</li>
 *   <li>В рамках группы (поле {@code group} указывает на конкретную группу)</li>
 * </ul>
 *
 * <p>Пост обязательно содержит текст и всегда связан с автором.
 * Изображение — опциональное дополнение к тексту.</p>
 *
 * <p>Таблица БД: {@code posts}</p>
 *
 * @see User
 * @see Group
 */
@Entity
// Объявляет класс управляемой JPA-сущностью. Hibernate будет отслеживать все изменения
// объектов этого типа в пределах активного Persistence Context (обычно — в рамках транзакции).
@Table(name = "posts")
// Явно задаём имя таблицы "posts" в snake_case — стандарт именования в SQL.
@Getter
// Lombok: генерирует геттеры для всех полей — getId(), getText(), getAuthor() и т.д.
@Setter
// Lombok: генерирует сеттеры для всех полей — setText(), setAuthor() и т.д.
@Builder
// Lombok: паттерн Builder — Post.builder().text("Привет!").author(user).build()
// Особенно удобен, когда объект имеет много опциональных полей (imageUrl, group).
@NoArgsConstructor
// Lombok: конструктор без аргументов, обязательный для JPA-сущностей.
// Hibernate использует его при загрузке сущностей из БД через рефлексию.
@AllArgsConstructor
// Lombok: конструктор со всеми полями, необходимый для работы @Builder.
public class Post {

    /**
     * Уникальный идентификатор поста, генерируется базой данных автоматически.
     */
    @Id
    // Первичный ключ таблицы "posts"
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    // IDENTITY: БД сама генерирует и инкрементирует значение (AUTO_INCREMENT / SERIAL).
    // id будет null до первого сохранения объекта в БД через репозиторий.
    private Long id;

    /**
     * Автор поста — пользователь, создавший публикацию.
     * Является обязательным полем: каждый пост принадлежит конкретному пользователю.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    // @ManyToOne: связь "многие к одному" — один пользователь может иметь много постов,
    // каждый пост принадлежит ровно одному автору.
    // fetch = FetchType.LAZY: "ленивая" загрузка — объект User НЕ загружается из БД
    // вместе с постом. Он будет загружен только при первом обращении к полю author.
    // Это критично для производительности: при загрузке ленты из 50 постов мы не хотим
    // выполнять 50 дополнительных запросов за данными авторов (проблема N+1).
    @JoinColumn(name = "author_id", nullable = false)
    // @JoinColumn задаёт имя колонки внешнего ключа в таблице "posts".
    // nullable = false: в БД создаётся ограничение NOT NULL — пост без автора недопустим.
    private User author;

    /**
     * Группа, в которой опубликован пост.
     * Если {@code null} — пост опубликован в личной ленте пользователя (не в группе).
     * Если задан — пост является записью конкретного сообщества.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    // @ManyToOne: одна группа может содержать много постов.
    // LAZY-загрузка по тем же соображениям производительности, что и для author.
    @JoinColumn(name = "group_id")
    // nullable не указан — по умолчанию допускает NULL.
    // NULL в group_id означает: пост в личной ленте, а не в группе.
    // Это более гибкий подход, чем создание отдельных таблиц для постов в ленте и в группах.
    private Group group;

    /**
     * Текстовое содержимое поста.
     * Обязательное поле — пост должен содержать хотя бы текст.
     * Длина не ограничена — пользователь может написать длинный пост.
     */
    @Column(columnDefinition = "TEXT", nullable = false)
    // columnDefinition = "TEXT": тип колонки в БД — TEXT (без ограничения длины).
    // nullable = false: текст обязателен даже при наличии изображения.
    // Это архитектурное решение: пустой текст с картинкой может быть нежелательным контентом.
    private String text;

    /**
     * URL прикреплённого изображения к посту.
     * Хранится как ссылка на файл в объектном хранилище (S3, MinIO и т.п.),
     * а не само изображение в виде двоичных данных в БД.
     * {@code null} если изображение не прикреплено.
     */
    @Column(name = "image_url", columnDefinition = "TEXT")
    // image_url: обнуляемое поле — изображение не обязательно (текстовый пост без картинки).
    // TEXT вместо VARCHAR(255): URL к CDN или подписанные S3-ссылки могут превышать 255 символов.
    private String imageUrl;

    /**
     * Дата и время создания поста.
     * Устанавливается автоматически Hibernate при выполнении INSERT.
     * После создания не изменяется.
     */
    @CreationTimestamp
    // Hibernate выставляет текущее время при INSERT — надёжнее, чем делать это в сервисном слое,
    // так как значение фиксируется в момент записи в БД.
    @Column(name = "created_at", updatable = false)
    // updatable = false: запрещает изменение этого поля при UPDATE.
    // Дата публикации — исторический факт, который нельзя изменить.
    private LocalDateTime createdAt;

    /**
     * Дата и время последнего редактирования поста.
     * Обновляется автоматически Hibernate при каждом изменении поста.
     * Позволяет интерфейсу показывать пометку "изменено" рядом с постом.
     */
    @UpdateTimestamp
    // Hibernate автоматически обновляет это поле при каждом UPDATE поста.
    // Если пользователь отредактировал текст — updatedAt получит актуальное время.
    @Column(name = "updated_at")
    private LocalDateTime updatedAt;
}
