package com.socialnetwork.exception;

/**
 * Исключение для операций, запрещённых из-за недостаточных прав (HTTP 403 Forbidden).
 *
 * <p>Бросается в сервисном слое при попытке выполнить действие без необходимых прав:
 * редактировать чужой пост, удалять чужой комментарий, выполнять операцию от имени другого пользователя.
 *
 * <p>Отличие от 401 Unauthorized:
 * <ul>
 *   <li>401 — пользователь не аутентифицирован (нет токена или токен невалиден)</li>
 *   <li>403 — пользователь аутентифицирован, но не имеет прав на данное действие</li>
 * </ul>
 *
 * <p>{@link GlobalExceptionHandler} перехватывает это исключение
 * и возвращает клиенту HTTP 403 с сообщением из конструктора.
 */
public class ForbiddenException extends RuntimeException {

    /**
     * @param message описание запрещённой операции (возвращается клиенту в ответе)
     */
    public ForbiddenException(String message) {
        super(message);
    }
}
